/**
 * @class Keyboard
 * @description Tracks the current state of all relevant keyboard inputs.
 * Each property is true while the corresponding key is pressed.
 */
class Keyboard {

    /** @type {boolean} Whether the space bar is currently pressed */
    SPACE = false;

    /** @type {boolean} Whether the left arrow key is currently pressed */
    LEFT = false;

    /** @type {boolean} Whether the up arrow key is currently pressed */
    UP = false;

    /** @type {boolean} Whether the right arrow key is currently pressed */
    RIGHT = false;

    /** @type {boolean} Whether the down arrow key is currently pressed */
    DOWN = false; 

    /** @type {boolean} Whether the D key is currently pressed */
    D = false;
}